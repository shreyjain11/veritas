type ItemStatus = "stable" | "sensitive" | "wrong" | "error";
type Row = {
  item: V2Item;
  response: V2Response | undefined;
  correct: boolean | null;
  variants: Array<{ transformation: V2Transformation; response: V2Response | undefined; correct: boolean | null }>;
  status: ItemStatus;
};

const FILTERS: Array<{ id: "all" | ItemStatus; label: string; hint: string }> = [
  { id: "all", label: "All", hint: "every canonical item" },
  { id: "sensitive", label: "Flipped by a variant", hint: "correct on the original, wrong on at least one variant" },
  { id: "wrong", label: "Wrong on original", hint: "incorrect on the canonical prompt" },
  { id: "error", label: "Errors", hint: "missing or failed responses (excluded from scores)" },
];

const STATUS_DOT: Record<ItemStatus, string> = {
  stable: "bg-iris",
  sensitive: "bg-warn",
  wrong: "bg-faint",
  error: "bg-danger",
};

function useRows(report: V2Report): Row[] {
  return useMemo(() => {
    const responses = new Map(report.responses.map((response) => [response.item_id, response]));
    const byParent = new Map<string, V2Transformation[]>();
    for (const transformation of report.transformations) {
      byParent.set(transformation.parent_item_id, [...(byParent.get(transformation.parent_item_id) ?? []), transformation]);
    }
    return report.benchmark.items.map((item) => {
      const response = responses.get(item.id);
      const correct = isCorrect(response, item.expected_output);
      const variants = (byParent.get(item.id) ?? []).map((transformation) => {
        const variantResponse = responses.get(transformation.child_item_id);
        return { transformation, response: variantResponse, correct: isCorrect(variantResponse, transformation.expected_output) };
      });
      const status: ItemStatus = correct === null ? "error" : !correct ? "wrong" : variants.some((v) => v.correct === false) ? "sensitive" : "stable";
      return { item, response, correct, variants, status };
    });
  }, [report]);
}

function Verdict({ correct }: { correct: boolean | null }) {
  if (correct === null) return <Chip tone="danger">error</Chip>;
  return correct ? <Chip tone="iris">correct</Chip> : <Chip tone="warn">wrong</Chip>;
}

const PAGE = 200;

function ItemExplorer({ report }: { report: V2Report }) {
  const rows = useRows(report);
  const [filter, setFilter] = useState<"all" | ItemStatus>("all");
  const [query, setQuery] = useState("");
  const [selectedId, setSelectedId] = useState<string | null>(null);
  const [limit, setLimit] = useState(PAGE);
  const counts = useMemo(() => {
    const result: Record<string, number> = { all: rows.length };
    for (const row of rows) result[row.status] = (result[row.status] ?? 0) + 1;
    return result;
  }, [rows]);
  const visible = useMemo(() => {
    const needle = query.trim().toLowerCase();
    return rows.filter((row) => (filter === "all" || row.status === filter) && (!needle || `${row.item.id} ${promptText(row.item.prompt)}`.toLowerCase().includes(needle)));
  }, [rows, filter, query]);
  useEffect(() => setLimit(PAGE), [filter, query]);
  const selected = visible.find((row) => row.item.id === selectedId) ?? visible[0] ?? null;

  return (
    <section>
      <div className="flex flex-wrap items-end justify-between gap-3">
        <div>
          <h2 className="font-display text-[1.375rem] font-medium tracking-[-0.01em] text-fg">Items, responses, and variants</h2>
          <p className="mt-1 text-sm text-muted">See exactly which prompts flipped under which transformation.</p>
        </div>
        <input value={query} onChange={(event) => setQuery(event.target.value)} placeholder="Search id or prompt…" aria-label="Search benchmark items" className="w-full rounded-md border border-line bg-base px-3 py-2 text-sm text-fg outline-none focus:border-iris/60 sm:w-64" />
      </div>
      <div className="mt-3 flex flex-wrap gap-2" role="tablist" aria-label="Filter items">
        {FILTERS.map((entry) => (
          <button
            key={entry.id}
            type="button"
            role="tab"
            aria-selected={filter === entry.id}
            title={entry.hint}
            onClick={() => setFilter(entry.id)}
            className={`rounded-full border px-3 py-1 text-xs transition-colors ${filter === entry.id ? "border-iris/60 bg-iris-dim text-iris-fg" : "border-line text-secondary hover:border-edge hover:text-fg"}`}
          >
            {entry.label} <span className="tnum font-mono text-muted">{counts[entry.id] ?? 0}</span>
          </button>
        ))}
      </div>
      <div className="mt-4 grid overflow-hidden rounded-lg border border-line bg-surface lg:grid-cols-[320px_1fr]">
        <div className="max-h-[620px] overflow-y-auto border-b border-line lg:border-b-0 lg:border-r">
          {visible.length === 0 && <p className="p-4 text-sm text-muted">No items match.</p>}
          {visible.slice(0, limit).map((row) => (
            <button
              type="button"
              key={row.item.id}
              onClick={() => setSelectedId(row.item.id)}
              aria-current={selected?.item.id === row.item.id}
              className={`flex w-full gap-3 border-b border-hairline px-4 py-3 text-left transition-colors ${selected?.item.id === row.item.id ? "bg-iris-dim/40" : "hover:bg-elevated/50"}`}
            >
              <span aria-hidden className={`mt-1.5 size-2 shrink-0 rounded-full ${STATUS_DOT[row.status]}`} />
              <span className="min-w-0">
                <span className="block truncate font-mono text-xs text-fg">{row.item.id}</span>
                <span className="mt-1 line-clamp-2 block text-xs leading-relaxed text-muted">{promptText(row.item.prompt)}</span>
              </span>
            </button>
          ))}
          {visible.length > limit && (
            <button type="button" onClick={() => setLimit(limit + PAGE)} className="w-full px-4 py-3 text-xs text-iris-fg hover:bg-elevated/50">
              Show {Math.min(PAGE, visible.length - limit)} more of {visible.length - limit}
            </button>
          )}
        </div>
        <div className="min-h-80 min-w-0 p-5">{selected ? <ItemDetail row={selected} /> : <p className="text-sm text-muted">Select an item.</p>}</div>
      </div>
    </section>
  );
}

function ItemDetail({ row }: { row: Row }) {
  const { item, response, correct } = row;
  return (
    <div className="space-y-5">
      <div className="flex flex-wrap items-center gap-2">
        <span className="break-all font-mono text-xs text-muted">{item.id}</span>
        <Verdict correct={correct} />
        <span className="font-mono text-[0.6875rem] text-muted">{row.variants.length} variant{row.variants.length === 1 ? "" : "s"}</span>
      </div>
      <Field label="Prompt" value={promptText(item.prompt)} />
      {item.choices?.length ? (
        <div>
          <p className="text-xs font-medium text-muted">Choices</p>
          <ul className="mt-2 space-y-1 font-mono text-sm">
            {item.choices.map((choice) => (
              <li key={choice.id} className={choice.id === item.expected_output ? "text-iris-fg" : "text-secondary"}>
                {choice.id}. {choice.text}
                {choice.id === item.expected_output ? "  ← key" : ""}
              </li>
            ))}
          </ul>
        </div>
      ) : null}
      <div className="grid gap-4 sm:grid-cols-2">
        <Field label="Expected" value={answerText(item.expected_output)} />
        <Field label="Parsed answer" value={response?.error ? "excluded (error)" : answerText(response?.parsed_answer)} />
      </div>
      <Field label="Raw model response" value={response?.error ? `Error: ${response.error}` : response?.raw_text || "(empty)"} />
      <div className="flex flex-wrap gap-4 font-mono text-xs text-muted">
        <span>{response?.token_count ?? "—"} tokens</span>
        <span>{response?.latency_ms != null ? `${response.latency_ms.toFixed(0)} ms` : "— ms"}</span>
        <span>{response?.token_logprobs?.length ?? 0} log probabilities</span>
      </div>
      {row.variants.length ? (
        <div>
          <p className="text-xs font-medium text-muted">Variants</p>
          <div className="mt-2 space-y-2">
            {row.variants.map(({ transformation, response: variant, correct: variantCorrect }) => (
              <details key={transformation.child_item_id} className="rounded-md border border-line p-3" open={variantCorrect === false && correct === true}>
                <summary className="flex cursor-pointer flex-wrap items-center gap-2 text-xs">
                  <span className="font-mono text-secondary">{transformation.family}</span>
                  <Chip>{transformation.validation}</Chip>
                  <Verdict correct={variantCorrect} />
                  <span className="font-mono text-muted">
                    key {answerText(transformation.expected_output)} · answered {variant?.error ? "—" : answerText(variant?.parsed_answer)}
                  </span>
                </summary>
                <div className="mt-3 space-y-3">
                  <Field label="Variant prompt" value={requestPrompt(variant) ?? "Not recorded by this adapter."} />
                  <Field label="Variant response" value={variant?.error ? `Error: ${variant.error}` : variant?.raw_text || "(empty)"} />
                </div>
              </details>
            ))}
          </div>
        </div>
      ) : null}
    </div>
  );
}

function Field({ label, value }: { label: string; value: string }) {
  return (
    <div className="min-w-0">
      <p className="text-xs font-medium text-muted">{label}</p>
      <pre className="mt-2 max-h-72 overflow-auto whitespace-pre-wrap break-words rounded-md bg-elevated/50 p-3 font-mono text-xs leading-relaxed text-secondary">{value}</pre>
    </div>
  );
}

function EvidenceMatrix({ report }: { report: V2Report }) {
  if (!report.evidence_matrix.length) return null;
  return (
    <section>
      <h2 className="font-display text-[1.375rem] font-medium tracking-[-0.01em] text-fg">Evidence matrix</h2>
      <p className="mt-1 text-sm text-muted">Which detectors bear on each hypothesis, and what they found.</p>
      <div className="mt-4 overflow-x-auto rounded-lg border border-line bg-surface">
        <table className="w-full min-w-[640px] text-left text-sm">
          <thead className="bg-subtle text-xs text-muted">
            <tr><th className="p-3 font-medium">Hypothesis</th><th className="p-3 font-medium">Supporting</th><th className="p-3 font-medium">Against</th><th className="p-3 font-medium">Unavailable</th><th className="p-3 font-medium">Confidence</th></tr>
          </thead>
          <tbody>
            {report.evidence_matrix.map((row) => (
              <tr key={row.hypothesis} className="border-t border-line">
                <td className="p-3 text-fg">{row.hypothesis}</td>
                <td className="p-3 font-mono text-xs text-secondary">{row.supporting.join(", ") || "—"}</td>
                <td className="p-3 font-mono text-xs text-secondary">{row.contradicting.join(", ") || "—"}</td>
                <td className="p-3 font-mono text-xs text-muted">{row.unavailable.join(", ") || "—"}</td>
                <td className="p-3"><Chip tone={CONFIDENCE_TONE[row.confidence] ?? "neutral"}>{row.confidence.replaceAll("_", " ")}</Chip></td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    </section>
  );
}

