type Tone = "iris" | "warn" | "danger" | "neutral";
const TONES: Record<Tone, string> = {
  iris: "border-iris/30 bg-iris-dim text-iris-fg",
  warn: "border-warn/30 bg-warn-dim text-warn-fg",
  danger: "border-danger/30 bg-danger-dim text-danger-fg",
  neutral: "border-line bg-elevated text-secondary",
};

function Chip({ tone = "neutral", children }: { tone?: Tone; children: React.ReactNode }) {
  return <span className={`inline-flex items-center whitespace-nowrap rounded-full border px-2 py-0.5 text-xs font-medium ${TONES[tone]}`}>{children}</span>;
}

const VERDICT: Record<string, { label: string; tone: Tone }> = {
  supports: { label: "dependence detected", tone: "warn" },
  contradicts: { label: "robust", tone: "iris" },
  inconclusive: { label: "inconclusive", tone: "neutral" },
};

function verdictOf(finding: V2Finding): { label: string; tone: Tone } {
  if (finding.status !== "complete") return { label: finding.status.replaceAll("_", " "), tone: "neutral" };
  if (finding.detector_id === "exact_match" && finding.direction === "supports") return { label: "overlap found", tone: "warn" };
  return VERDICT[finding.direction] ?? { label: finding.direction, tone: "neutral" };
}

const CONFIDENCE_TONE: Record<string, Tone> = {
  direct: "warn",
  strong_indirect: "warn",
  weak_indirect: "warn",
  against: "iris",
};

